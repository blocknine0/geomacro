-- =============================================================================
-- Geomacro private commercial revenue delivery ledger
--
-- PURPOSE
-- - preserve one detailed, private, immutable proof row for every reconciled
--   real commercial earning
-- - bind payment -> settlement -> exact delivered intelligence -> usage evidence
-- - make the ledger append-only and tamper-evident with a SHA-256 hash chain
-- - keep internal canaries/testnet/sandbox activity out of the revenue ledger
--
-- PRIVATE BOUNDARY
-- - service-role read access only; no public/anon/authenticated access
-- - never stores raw payment signatures/tokens, private keys, API credentials,
--   auth headers, facilitator secrets or wallet private material
-- - payer identity remains hashed; the exact buyer-visible response is preserved
--   privately because it is the core proof of what Geomacro delivered
-- =============================================================================

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.private_commercial_revenue_delivery_ledger (
  id uuid primary key default gen_random_uuid(),
  sequence_no bigint generated by default as identity unique,
  recorded_at timestamptz not null default now(),

  payment_event_id uuid not null unique
    references public.commercial_payment_events(id) on delete restrict,
  usage_event_id uuid
    references public.commercial_usage_events(id) on delete restrict,

  payment_occurred_at timestamptz not null,
  settled_at timestamptz not null,
  delivered_at timestamptz not null,
  reconciled_at timestamptz not null,

  environment text not null,
  provider text not null,
  provider_environment text,
  purchase_classification text not null,
  payment_method text not null,

  principal_id uuid,
  entitlement_grant_id uuid,
  offer_id text,
  tier text,

  network_family text not null,
  network_name text,
  chain_id text,
  settlement_network text,

  asset_symbol text,
  asset_contract text,
  amount_atomic numeric(78,0),
  amount_decimal numeric(38,18),
  settlement_currency text,
  settlement_amount numeric(38,8),
  fee_currency text,
  provider_fee_amount numeric(38,8),
  geomacro_fee_amount numeric(38,8),

  provider_order_id text,
  provider_payment_id text,
  provider_settlement_id text not null,
  settlement_reference_sha256 text not null,
  tx_hash text,
  block_number numeric(30,0),
  confirmations integer,

  payer_reference_hash text,
  recipient_reference_hash text,

  delivery_ledger text not null,
  delivery_record_id uuid not null,
  payment_fingerprint_sha256 text,
  request_fingerprint_sha256 text,
  request_id text not null,
  client_request_id text,
  product_id text not null,
  capability text not null,
  subject_type text,
  subject_key text,

  query_plan_hash text,
  delivered_product_hash text not null,
  response_sha256 text not null,
  delivery_snapshot_sha256 text not null,

  risk_object_id text,
  risk_object_version text,
  risk_object_signed boolean not null default false,
  risk_gate_included boolean not null default false,
  risk_gate_decision text,
  idempotent_replay boolean not null default false,
  execution_authorized boolean not null default false,

  reconciliation_reference text not null,
  revenue_classification text not null,
  commercial_revenue boolean not null,

  -- Exact buyer-visible delivered response. This is deliberately private and is
  -- never exposed by public proof/dashboard surfaces.
  private_delivery_snapshot jsonb not null,

  -- Canonical internal proof envelope used to compute the tamper-evident chain.
  proof_document jsonb not null,
  previous_entry_sha256 text,
  entry_sha256 text not null unique,

  constraint private_revenue_environment_check
    check (environment in ('mainnet','fiat')),
  constraint private_revenue_purchase_classification_check
    check (purchase_classification in ('external_customer','independent_production_buyer')),
  constraint private_revenue_delivery_ledger_check
    check (delivery_ledger in ('coinbase_x402_deliveries','agent_commerce_deliveries')),
  constraint private_revenue_settlement_hash_check
    check (settlement_reference_sha256 ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_payment_hash_check
    check (payment_fingerprint_sha256 is null or payment_fingerprint_sha256 ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_request_hash_check
    check (request_fingerprint_sha256 is null or request_fingerprint_sha256 ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_query_plan_hash_check
    check (query_plan_hash is null or query_plan_hash ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_product_hash_check
    check (delivered_product_hash ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_response_hash_check
    check (response_sha256 ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_snapshot_hash_check
    check (delivery_snapshot_sha256 ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_previous_hash_check
    check (previous_entry_sha256 is null or previous_entry_sha256 ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_entry_hash_check
    check (entry_sha256 ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_payer_hash_check
    check (payer_reference_hash is null or payer_reference_hash ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_recipient_hash_check
    check (recipient_reference_hash is null or recipient_reference_hash ~ '^[0-9a-f]{64}$'),
  constraint private_revenue_reconciliation_check
    check (revenue_classification = 'commercial_revenue' and commercial_revenue = true),
  constraint private_revenue_execution_boundary_check
    check (execution_authorized = false),
  constraint private_revenue_amount_check
    check (amount_atomic is null or amount_atomic > 0),
  constraint private_revenue_request_id_check
    check (char_length(request_id) between 8 and 160),
  constraint private_revenue_product_id_check
    check (char_length(product_id) between 3 and 128),
  constraint private_revenue_capability_check
    check (char_length(capability) between 2 and 80)
);

