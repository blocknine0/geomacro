-- Append-only means even service-role application code cannot silently rewrite
-- or delete proof. Database-owner break-glass administration remains outside the
-- application contract.
create or replace function public.guard_private_commercial_revenue_delivery_ledger()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  raise exception 'private commercial revenue delivery ledger is append-only';
end;
$$;

revoke all on function public.guard_private_commercial_revenue_delivery_ledger()
  from PUBLIC, anon, authenticated, service_role;

