-- Independent verifier: recompute every entry hash and every previous-link from
-- stored proof documents. It does not mutate the ledger.
create or replace function public.verify_private_commercial_revenue_delivery_ledger()
returns table (
  sequence_no bigint,
  payment_event_id uuid,
  stored_previous_entry_sha256 text,
  expected_previous_entry_sha256 text,
  stored_entry_sha256 text,
  recomputed_entry_sha256 text,
  previous_link_valid boolean,
  entry_hash_valid boolean
)
language sql
security definer
set search_path = public, extensions
as $$
  with ordered as (
    select
      l.sequence_no,
      l.payment_event_id,
      l.previous_entry_sha256,
      l.entry_sha256,
      l.proof_document,
      lag(l.entry_sha256) over (order by l.sequence_no) as expected_previous
    from public.private_commercial_revenue_delivery_ledger l
  )
  select
    o.sequence_no,
    o.payment_event_id,
    o.previous_entry_sha256,
    o.expected_previous,
    o.entry_sha256,
    encode(
      extensions.digest(
        convert_to(
          coalesce(o.expected_previous, 'GENESIS') || '|' || o.proof_document::text,
          'UTF8'
        ),
        'sha256'
      ),
      'hex'
    ) as recomputed_entry_sha256,
    o.previous_entry_sha256 is not distinct from o.expected_previous as previous_link_valid,
    o.entry_sha256 = encode(
      extensions.digest(
        convert_to(
          coalesce(o.expected_previous, 'GENESIS') || '|' || o.proof_document::text,
          'UTF8'
        ),
        'sha256'
      ),
      'hex'
    ) as entry_hash_valid
  from ordered o
  order by o.sequence_no;
$$;

