import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const path=".github/workflows/phase2h-private-raw-archive.yml";
test("Phase 2H B2 workflow requires archive-only provider approval and four six-hour quota-first archive slots",()=>{
 const yaml=readFileSync(path,"utf8");
 assert.ok(yaml.includes('cron: "29 0,6,12,18 * * *"'));
 assert.ok(yaml.includes("github.event.schedule == '29 0,6,12,18 * * *'"));
 assert.doesNotMatch(yaml,/archive-then-retention:/u);
 assert.doesNotMatch(yaml,/five-hour-slot:|cron: "21/u);
 assert.doesNotMatch(yaml,/workflow_dispatch:|manual-smoke-gate:|RUN_ONCE_PHASE2H/u);
 assert.match(yaml,/Automatic D1 raw-news deletion is PAUSED/u);
 assert.match(yaml,/Every six hours: bounded pending original archive/u);
 const manual=readFileSync(".github/workflows/phase2h-manual-d1-storage-cleanup.yml","utf8");
 assert.match(manual,/workflow_dispatch:/u);
 assert.match(manual,/default: DO_NOT_DELETE/u);
 assert.doesNotMatch(manual,/\n  schedule:\s/u);
 assert.match(yaml,/maintenance: \$\{\{ steps\.provider\.outputs\.maintenance \}\}/u);
 assert.match(yaml,/needs\.quota-admission\.outputs\.raw_archive == 'true'/u);
 assert.match(yaml,/raw_archive: \$\{\{ steps\.provider\.outputs\.phase2h_raw_archive \}\}/u);
 assert.match(yaml,/PHASE2H_PROVIDER_MAINTENANCE: \$\{\{ needs\.quota-admission\.outputs\.raw_archive \}\}/u);
 assert.doesNotMatch(yaml,/needs\.quota-admission\.outputs\.structural_snapshot/u);
 assert.doesNotMatch(yaml,/\n  push:\s/u);
 assert.match(yaml,/B2_REQUEST_BUDGET: "12"/u);
 assert.match(yaml,/Publish Phase2H archive admission truth without an extra provider request/u);
 assert.match(yaml,/ARCHIVE_HELD_NOT_VERIFIED/u);
 assert.match(yaml,/ADMITTED_PENDING_B2_PROOF/u);
 assert.match(yaml,/QUOTA_MEASUREMENT_FAILED_NO_ARCHIVE_PROOF/u);
 assert.match(yaml,/green workflow is NOT end-to-end archival acceptance/u);
 assert.match(yaml,/GITHUB_STEP_SUMMARY/u);
});
