CREATE TABLE IF NOT EXISTS p1_source_to_cell (
 source_id TEXT NOT NULL REFERENCES source_registry(source_id),
 country_iso3 TEXT NOT NULL,
 primary_category TEXT NOT NULL,
 rank INTEGER NOT NULL CHECK(rank BETWEEN 1 AND 3),
 origin TEXT NOT NULL DEFAULT 'EXPLICIT_REGISTERED' CHECK(origin IN ('EXPLICIT_REGISTERED','VERIFIED_ALTERNATIVE')),
 PRIMARY KEY(source_id,country_iso3,primary_category),
 FOREIGN KEY(country_iso3,primary_category) REFERENCES p1_country_category_cells(country_iso3,primary_category)
);
CREATE INDEX IF NOT EXISTS idx_p1_cell_source ON p1_source_to_cell(country_iso3,primary_category,rank);
-- Seed only real source registry entries with a SPECIFIC country. GLOBAL
-- sources do NOT become 195 invented country-specific article evidence.
INSERT OR IGNORE INTO p1_source_to_cell(source_id,country_iso3,primary_category,rank)
SELECT source_id,country_iso3,intended_category,
 CASE WHEN ordinal<=2 THEN ordinal ELSE 3 END
FROM (
 SELECT source_id,country_iso3,intended_category,
 ROW_NUMBER() OVER (PARTITION BY country_iso3,intended_category ORDER BY source_id) AS ordinal
 FROM source_registry WHERE enabled=1 AND country_iso3 <> 'GLOBAL'
) WHERE ordinal<=3;
CREATE VIEW IF NOT EXISTS p1_source_cell_mapping_health AS
SELECT c.country_iso3,c.primary_category,
 COALESCE(SUM(CASE WHEN m.rank IN (1,2) THEN 1 ELSE 0 END),0) AS primary_sources,
 COALESCE(SUM(CASE WHEN m.rank=3 THEN 1 ELSE 0 END),0) AS secondary_sources
FROM p1_country_category_cells AS c
LEFT JOIN p1_source_to_cell AS m
 ON m.country_iso3=c.country_iso3 AND m.primary_category=c.primary_category
GROUP BY c.country_iso3,c.primary_category;
